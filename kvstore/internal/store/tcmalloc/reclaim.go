package tcmalloc

// ══════════════════════════════════════════════════════════════
// QSBR — Quiescent-State-Based Reclamation (замена time-based grace, баг T2)
// ══════════════════════════════════════════════════════════════
//
// ПРОБЛЕМА (T2). lock-free Get читает Handle из индекса, затем Resolve+decode
// из span-памяти. Между этими шагами горутину может вытеснить планировщик
// (async preemption) или остановить STW-пауза GC — на время дольше любого
// фиксированного grace-периода. Если параллельный Del/overwrite тем временем
// освободит слот, а Alloc переиспользует его, Get прочитает чужие/недописанные
// данные: use-after-free, torn-read или ложный not-found. storedKey-чек в Get
// ловит многое, но не всё (склейка старого ключа с новым значением).
//
// Старое решение — освобождать через фиксированные 100ms — неверно по сути:
// время ≠ гарантия завершения читателей.
//
// РЕШЕНИЕ — QSBR (как RCU в ядре Linux / userspace-RCU). Слот освобождается не
// по таймеру, а когда КАЖДЫЙ читатель гарантированно прошёл «тихое» состояние
// (quiescent state) после ретайра хендла.
//
// ─── Почему это дёшево именно здесь ───
//
// Модель сервера: каждый epoll-воркер — ОДНА горутина, обрабатывающая команды
// строго последовательно. Между командами (и пока воркер спит в epoll_wait) он
// НЕ держит ни одного хендла в span-память: Get копирует значение наружу до
// возврата. Это и есть естественная точка quiescence, доступная бесплатно.
//
//   - epoch                 — глобальное поколение, монотонно растёт (reclaim).
//   - workerEpoch[w]        — поколение, наблюдавшееся воркером w на последней
//                             границе команды; offlineEpoch = не в кворуме.
//   - ReportQuiescent(w)    — воркер online: публикует текущий epoch (граница
//                             обработки — проснулся из epoll_wait).
//   - GoOffline(w)          — воркер уходит спать в epoll_wait (держит nil).
//   - DeferFree(h)          — тегирует h текущим epoch (снят из индекса).
//   - reclaim()             — двигает epoch и освобождает батчи с тегом
//                             < min(наблюдаемое поколение по ОНЛАЙН-воркерам).
//
// ─── Почему это верно ───
//
// Читатель, наблюдавший хендл H, загрузил его из индекса ПОСЛЕ своего
// ReportQuiescent (online на поколении e): значит workerEpoch = e, и он online
// всё время, пока держит H (уходит offline/репортит заново только на границе
// команды, уже скопировав значение). Ретайр H произошёл не раньше загрузки, а
// поколение монотонно, поэтому tag(H) ≥ e. Пока читатель online на e:
//
//	min(online) ≤ e ≤ tag(H)   ⟹   tag(H) НЕ < min   ⟹   H не освобождается.
//
// Когда читатель дойдёт до следующей границы (репорт нового поколения) или
// уйдёт offline — он уже не держит H. Offline-воркеры исключены из кворума
// корректно: спящий в epoll_wait воркер не держит хендлов.
//
// ─── Idle-воркеры (liveness) ───
//
// Без offline спящий воркер заморозил бы свой epoch навсегда → min не растёт →
// reclaim встал бы (утечка pending). GoOffline перед epoll_wait исключает его
// из кворума, поэтому reclaim продолжает освобождать. Безопасно: он держит nil.

// offlineEpoch — значение слота воркера, означающее «спит, вне кворума».
// Реальные поколения начинаются с 1, поэтому 0 — безопасный сентинел.
const offlineEpoch uint64 = 0

// retireBatch — партия отложенных хендлов, помеченная поколением, в котором они
// были сняты из индекса (ретайрнуты). Освобождается целиком, когда поколение
// прошло кворум quiescence.
type retireBatch struct {
	gen     uint64
	handles []Handle
}

// ReportQuiescent помечает воркера online и публикует текущее поколение.
//
// Вызывается на границе обработки команд (воркер проснулся из epoll_wait и
// держит nil), ДО любого lock-free Get. Один atomic-store — вне горячего пути
// самого чтения.
func (s *TCMallocStore) ReportQuiescent(workerID int) {
	if workerID < 0 || workerID >= len(s.workerEpoch) {
		return
	}
	s.workerEpoch[workerID].Store(s.epoch.Load())
}

// GoOffline помечает воркера как спящего (вне кворума QSBR).
//
// Вызывается ПЕРЕД блокировкой в epoll_wait, когда воркер гарантированно не
// держит ни одного хендла (все команды обработаны, значения скопированы).
func (s *TCMallocStore) GoOffline(workerID int) {
	if workerID < 0 || workerID >= len(s.workerEpoch) {
		return
	}
	s.workerEpoch[workerID].Store(offlineEpoch)
}

// minObservedEpoch возвращает минимальное наблюдаемое поколение среди ОНЛАЙН-
// воркеров и флаг «есть хотя бы один онлайн». Offline-воркеры исключены.
func (s *TCMallocStore) minObservedEpoch() (min uint64, anyOnline bool) {
	min = ^uint64(0)
	for i := range s.workerEpoch {
		v := s.workerEpoch[i].Load()
		if v == offlineEpoch {
			continue
		}
		anyOnline = true
		if v < min {
			min = v
		}
	}
	return min, anyOnline
}

// reclaim — один цикл QSBR-освобождения (вызывается раз в ~100ms).
//
// Двигает поколение вперёд (чтобы онлайн-воркеры на следующей границе команды
// опубликовали новое значение и разблокировали текущие батчи) и освобождает все
// партии с тегом строго меньше кворумного минимума. Возвращает число
// освобождённых хендлов.
func (s *TCMallocStore) reclaim() int {
	// Новое поколение: ретайры теперь тегаются cur, а онлайн-воркеры, пройдя
	// границу команды, опубликуют cur → min поднимется → старые батчи уйдут.
	cur := s.epoch.Add(1)

	safe, anyOnline := s.minObservedEpoch()
	if !anyOnline {
		// Никто не онлайн → никто не держит хендлов. Безопасно освободить всё,
		// снятое из индекса до текущего поколения.
		safe = cur
	}

	s.deferMu.Lock()
	// Фильтр на месте: батчи с gen < safe освобождаем, остальные оставляем.
	// toFree — свежий слайс (не делит backing с pending) → нет T1-класса гонки
	// «append в живой backing затирает ещё не освобождённые хендлы».
	var toFree []Handle
	kept := s.pending[:0]
	for _, b := range s.pending {
		if b.gen < safe {
			toFree = append(toFree, b.handles...)
		} else {
			kept = append(kept, b)
		}
	}
	s.pending = kept
	s.deferMu.Unlock()

	for _, h := range toFree {
		s.caches[0].Free(s.heap, h)
	}
	return len(toFree)
}
